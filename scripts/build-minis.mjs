// Builds hooks/minis.ts from sheet/minis.js, the marks the slim band shows in place of Clawd.
//
//   node scripts/build-minis.mjs
//
// sheet/minis.js is a browser script (the design prototype loads it as is): it sets
// window.MINIS, one standalone animated SVG per task animation.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const window = {}
new Function('window', readFileSync(join(root, 'sheet/minis.js'), 'utf8'))(window)

const squash = svg => svg.replace(/\n\s*/g, ' ').replace(/\s+</g, '<').replace(/>\s+/g, '>')
const entries = Object.entries(window.MINIS).map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(squash(svg))},`)
writeFileSync(
  join(root, 'hooks/minis.ts'),
  `// Generated by scripts/build-minis.mjs from sheet/minis.js. Do not edit by hand.
// The slim band's marks: one abstract animated SVG per task animation, 16×11, scoped by class.

import type { AnimId } from '../types'

export const MINIS: Partial<Record<AnimId, string>> = {
${entries.join('\n')}
}
`,
)
console.log(`hooks/minis.ts: ${entries.length} marks`)
